// Offline only. Run against the local server; no paid provider calls.
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
  const browser=await chromium.launch({channel:'chrome',headless:true});
  const page=await browser.newPage({viewport:{width:1360,height:1000}});
  const errors=[],analysisRequests=[],discoveries=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(r.url().endsWith('/api/analyze'))analysisRequests.push(r);});
  await page.goto('http://127.0.0.1:8000');
  await page.getByRole('button',{name:'Discover Startups',exact:true}).click();
  await page.locator('#stages').selectOption('Seed');
  await page.locator('#sectors').selectOption('Enterprise Software / SaaS');
  await page.locator('#geographies').selectOption('Europe');
  const response=page.waitForResponse(r=>r.url().endsWith('/api/discover'));
  await page.locator('#discover-submit').click();
  const res=await response;assert.equal(res.status(),200);
  const report=await res.json(); discoveries.push(report);
  await page.locator('#startup-cards .card').last().waitFor();
  assert.equal(await page.locator('#startup-cards .card').count(),2);
  assert.equal(analysisRequests.length,0);
  assert.equal(report.usage.searches,0);assert.equal(report.duplicates_removed,1);
  const first=page.locator('#startup-cards .card').first();
  await first.getByText('Discovery evidence',{exact:true}).click();
  assert.ok((await first.locator('details a').first().getAttribute('href')).startsWith('https://synthetic-news.example'));
  fs.mkdirSync('.local',{recursive:true});
  await page.locator('#shortlist').scrollIntoViewIfNeeded();
  await page.screenshot({path:'.local/sourcing-shortlist.png'});
  await first.getByRole('button',{name:'Analyze company'}).click();
  assert.equal(await page.locator('#company').inputValue(),'https://lumen.example/');
  assert.equal(await page.locator('#mode').inputValue(),'demo');
  assert.equal(analysisRequests.length,0); // Selection prepares, never auto-spends.
  const analysis=page.waitForResponse(r=>r.url().endsWith('/api/analyze'));
  await page.locator('#analyze').click();
  assert.equal((await analysis).status(),200);
  await page.locator('#results').waitFor({state:'visible'});
  assert.equal(analysisRequests.length,1);
  assert.ok((await page.locator('#memo-content').textContent()).includes('SYNTHETIC FIXTURE'));
  await page.getByRole('button',{name:'Discover Startups',exact:true}).click();
  await page.getByText('Funding, company age & exclusions',{exact:true}).click();
  await page.locator('#keep-unknown-funding').uncheck();
  const refine=page.waitForResponse(r=>r.url().endsWith('/api/discover'));
  await page.locator('#discover-submit').click();
  const refined=await (await refine).json();assert.equal(refined.candidates.length,1);
  await page.locator('#exclude-companies').fill('lumen.example');
  const none=page.waitForResponse(r=>r.url().endsWith('/api/discover'));
  await page.locator('#discover-submit').click();
  assert.equal((await (await none).json()).candidates.length,0);
  await page.getByText('No candidates survived these evidence and mandate checks.',{exact:false}).waitFor();
  assert.equal(analysisRequests.length,1);
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({passed:true,initial_results:2,unknown_funding_excluded_results:1,company_excluded_results:0,analysis_handoff:'existing offline pipeline',automatic_analysis_calls:0,explicit_analysis_calls:1,browser_errors:errors},null,2));
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
